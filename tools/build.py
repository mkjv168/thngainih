#!/usr/bin/env python3
"""Deterministic static quiz pages and RAQM-shaped social cards."""
import html
import json
import os
import re
from pathlib import Path
KM = json.loads((Path(__file__).resolve().parent.parent / "site/i18n/km.json").read_text())
from string import Template
from urllib.parse import quote, urlencode, urlsplit
from PIL import Image, ImageDraw, ImageFont, features

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / 'site'
FONTS = ROOT / 'tools/fonts'

from cardlib import font, wrap, fitted

def card(path, result, quiz, base):
    color = result['color']
    rgb = tuple(int(color[i:i+2], 16) for i in (1, 3, 5))
    def linear(x):
        x /= 255
        return x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4
    while (1.05 / (sum(w * linear(c) for w, c in zip((.2126, .7152, .0722), rgb)) + .05)) < 4.5:
        rgb = tuple(int(c * .94) for c in rgb)
    im = Image.new('RGB', (1200, 630), rgb)
    draw = ImageDraw.Draw(im)
    draw.rounded_rectangle((1005, 55, 1145, 195), radius=42, outline='white', width=4)
    draw.text((1075, 125), result['name']['en'][0], font=font(70, True), fill='white', anchor='mm', language='en')
    def text(text, y, size, lang, bold=False, width=1070, max_lines=2):
        face, lines, size = fitted(draw, text, size, width, lang, bold, max_lines)
        for line in lines:
            draw.text((65, y), line, font=face, fill='white', language=lang, anchor='lt')
            y += int(size * 1.5)
        return y
    text(quiz['title']['km'], 48, 25, 'km', width=900, max_lines=1)
    text(result['name']['km'], 170, 88, 'km', True, max_lines=2)
    text(result['name']['en'], 385, 39, 'en', True, max_lines=1)
    text(result['tagline']['en'], 451, 27, 'en', max_lines=1)
    draw.line((65, 523, 1135, 523), fill='white', width=1)
    text(urlsplit(base).netloc + urlsplit(base).path.rstrip('/'), 542, 19, 'en', max_lines=1)
    text(KM['name'], 579, 22, 'km', max_lines=1)
    im.save(path, optimize=True)

def build():
    from siteconfig import CONFIG, STRINGS, base_url, local, template
    import shutil
    if not features.check('raqm'): raise SystemExit('Pillow RAQM required')
    base=base_url()
    # Generated: edit tools/site.json; analytics remains disabled until deployment.
    config_js="// Generated by tools/build.py from tools/site.json.\nwindow.SITE_CONFIG = "+json.dumps(dict(slug=CONFIG['slug'],name=local('name'),module='today',siteUrl=base,url=base,contentUrl='./data/content.json'))+";\n// Analytics OFF until deploy. At deploy: provider:'goatcounter', goatcounterCode:'thngainih'.\nwindow.ANALYTICS_CONFIG = {provider:'none', goatcounterCode:'', respectDNT:true, allowLocal:false, debug:false};\n"
    (SITE/'js/config.js').write_text(config_js)
    manifest=json.loads((SITE/'manifest.webmanifest').read_text())
    manifest.update(name=local('name'),short_name=local('name'),start_url=urlsplit(base).path+'?s=pwa',scope=urlsplit(base).path)
    (SITE/'manifest.webmanifest').write_text(json.dumps(manifest,indent=2)+'\n')
    for name,target in [('home.html','index.html'),('quiz.html','quiz/index.html'),('404.html','404.html'),('privacy.html','privacy/index.html')]:
        path=SITE/target;path.parent.mkdir(parents=True,exist_ok=True)
        source=template(name).replace('$base',html.escape(base)).replace('$brand',html.escape(local('name')))
        source=source.replace('$privacy_body',html.escape(local('privacy.body')))
        source=re.sub(r'<!-- og:start -->.*?<!-- og:end -->',lambda _:og_tags(base+('quiz/' if name=='quiz.html' else ''),base,local('quiz.title') if name=='quiz.html' else local('name')),source,flags=re.S)
        path.write_text(source)
    quiz=json.loads((SITE/'quiz/quiz.json').read_text())
    ids=[r['id'] for r in quiz['results']]
    order=quiz['tiebreak'] if isinstance(quiz['tiebreak'],list) else quiz['tiebreak']['fallback']
    assert set(order)==set(ids) and len(order)==len(ids)
    assert len(ids)==len(set(ids)) and all(re.fullmatch('[a-z0-9]+(?:-[a-z0-9]+)*',id) for id in ids)
    for q in quiz['questions']:
        assert q['answers']
        for a in q['answers']:assert all(id in ids and isinstance(n,(int,float)) for id,n in a['scores'].items())
    for folder in (SITE/'r').iterdir():
        if folder.is_dir() and folder.name not in ids:shutil.rmtree(folder)
    page=Template(template('result.html'))
    for result in quiz['results']:
        assert re.fullmatch('#[0-9a-fA-F]{6}',result['color'])
        folder=SITE/'r'/result['id'];folder.mkdir(parents=True,exist_ok=True)
        url=base+'r/'+result['id']+'/'
        share=url+'?'+urlencode({'src':'share','vs':result['id']})
        name=local(result['name']);name_km=local(result['name'],'km')
        tagline=local(result.get('blurb',result.get('tagline','')))
        title=local('quiz.resultHeadline').replace('{dish}',name)
        shareline=local(result.get('share',f"quiz.r.{result['id']}.share")).replace('{dish}',name)
        fields=dict(title=title,tagline=tagline,url=url,image=url+'og.png',alt=name+' / '+name_km,site_name=local('name'),id=result['id'],emoji=result['emoji'],name_en=name,name_km=name_km,description=local(result.get('fact',result.get('description',''))),encoded=quote(share,safe=''),facebook='https://www.facebook.com/sharer/sharer.php?'+urlencode({'u':share}),telegram='https://t.me/share/url?'+urlencode({'url':share,'text':shareline}))
        (folder/'index.html').write_text(page.substitute({k:html.escape(v,quote=True) for k,v in fields.items()}))
        display=dict(result,name={'en':name,'km':name_km},tagline={'en':shareline})
        card(folder/'og.png',display,dict(title={'km':local(quiz['title'],'km')}),base)
    (SITE/'r/index.json').write_text(json.dumps({'results':quiz['results']},ensure_ascii=False,indent=2)+'\n')
    from build_daily import render
    render(SITE/'og-image.png',None,base)
    print(f'Built {len(ids)} result pages + RAQM cards; base={base}')

def og_tags(url,base,title):
    esc=lambda v:html.escape(v,quote=True)
    return f'''<!-- og:start -->
<link rel="canonical" href="{esc(url)}"><meta property="og:url" content="{esc(url)}">
<meta property="og:title" content="{esc(title)}"><meta property="og:description" content="Your lunar date, holy days and traditional weekday colour.">
<meta property="og:type" content="website"><meta property="og:image" content="{esc(base)}og-image.png">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta property="og:image:type" content="image/png"><meta name="twitter:card" content="summary_large_image">
<!-- og:end -->'''

if __name__=='__main__':build()
